"""Fail-closed, read-only PRD 3.2 output review gate.

Use AFTER V5 and Qwen model inference. This does not change labels, masks, ROIs,
model prompts, or PRD 3.1. No human review/GT is accepted as an input.
A traceable request ID/target echo helps catch wiring mistakes, but does NOT prove
that the model visually attended to the requested garment.
"""
from __future__ import annotations

import hashlib
import json
import math
import re
from collections import Counter
from itertools import combinations
from typing import Any

ALLOWED_CLASSES = frozenset({"top", "pants", "skirt", "outerwear", "dress", "shoe", "bag", "accessory"})
FRAME_META = re.compile(
    r"红色(?:边框|框|标注框)|红框|(?:红色|蓝色)框内|框内展示|框选|"
    r"(?:red|blue)\s+(?:bounding\s+)?box|inside\s+the\s+(?:red|blue)\s+box",
    re.I,
)
ABSTENTION = re.compile(r"无法确定|无法判断|无法回答|不清楚|不知道|不确定|cannot determine|can't tell|unknown", re.I)


def _stable_hash(obj: Any) -> str:
    encoded = json.dumps(obj, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False).encode("utf-8")
    return hashlib.sha256(encoded).hexdigest()


def _valid_box(box: Any) -> bool:
    return (isinstance(box, (list, tuple)) and len(box) == 4
            and all(type(x) in (int, float) and math.isfinite(x) for x in box)
            and box[0] < box[2] and box[1] < box[3])


def _overlap_by_smaller_box(a: list[float], b: list[float]) -> float:
    intersection = max(0.0, min(a[2], b[2]) - max(a[0], b[0])) * max(0.0, min(a[3], b[3]) - max(a[1], b[1]))
    area_a = (a[2] - a[0]) * (a[3] - a[1])
    area_b = (b[2] - b[0]) * (b[3] - b[1])
    return intersection / min(area_a, area_b)


def _payload(envelope: Any) -> Any:
    if isinstance(envelope, dict) and "payload" in envelope:
        return envelope["payload"]
    return envelope


def _tags(envelope: Any) -> dict[str, Any] | None:
    raw = _payload(envelope)
    if isinstance(raw, dict):
        return raw
    if not isinstance(raw, str):
        return None
    text = raw.strip()
    if text.startswith("```json") and text.endswith("```"):
        text = text[len("```json"):-3].strip()
    elif text.startswith("```") and text.endswith("```"):
        text = text[3:-3].strip()
    try:
        parsed = json.loads(text)
    except (ValueError, TypeError):
        return None
    return parsed if isinstance(parsed, dict) else None


def _text(envelope: Any) -> str:
    value = _payload(envelope)
    return value.strip() if isinstance(value, str) else ""


def _binding_issues(case: str, instance: str, request: str | None, task: str,
                    envelope: Any) -> list[str]:
    """Only validates application-provided routing metadata (not Qwen self-claims)."""
    if not isinstance(envelope, dict) or "payload" not in envelope:
        return [f"{task}_ROUTING_UNVERIFIED"]
    expected = {"case_id": case, "target_instance_id": instance}
    if request is not None:
        expected["request_id"] = request
    issues = []
    for key, correct in expected.items():
        if key not in envelope:
            issues.append(f"{task}_{key.upper()}_MISSING")
        elif envelope[key] != correct:
            issues.append(f"{task}_{key.upper()}_MISMATCH")
    return issues


def guard_outputs(items: list[dict[str, Any]], *, duplicate_overlap: float = .85) -> dict[str, Any]:
    """Return non-mutating risk flags and original records, with no automatic release.

    Input rows: case_id, instance_id, v5_category, tags, vqa, copy; optional
    bbox_xyxy (source image), duplicate_candidate (upstream risk flag),
    vqa_question, request_id. Task results may be bare legacy strings/dicts or
    envelopes {case_id,target_instance_id,request_id,payload}. The envelope
    metadata must originate from service routing, NOT text generated by Qwen.
    """
    if not isinstance(items, list) or not items:
        raise ValueError("expected a nonempty array of service records")
    if not 0 < duplicate_overlap <= 1:
        raise ValueError("duplicate_overlap must be in (0,1]")
    seen: set[tuple[str, str]] = set()
    outputs = []
    for i, item in enumerate(items):
        if not isinstance(item, dict):
            raise ValueError(f"row {i}: expected object")
        case, inst = item.get("case_id"), item.get("instance_id")
        if not isinstance(case, str) or not case.strip() or not isinstance(inst, str) or not inst.strip():
            raise ValueError(f"row {i}: missing case_id/instance_id")
        key = (case, inst)
        if key in seen:
            raise ValueError(f"duplicate record identity: {case}__{inst}")
        seen.add(key)
        bbox = item.get("bbox_xyxy")
        reasons = []
        if bbox is not None and not _valid_box(bbox):
            reasons.append("INVALID_PREDICTED_BBOX")
        v5 = item.get("v5_category")
        tags = _tags(item.get("tags"))
        if v5 not in ALLOWED_CLASSES:
            reasons.append("INVALID_V5_CATEGORY")
        if tags is None:
            reasons.append("TAGS_NOT_JSON_OBJECT")
        else:
            qwen_category = tags.get("category")
            if qwen_category not in ALLOWED_CLASSES:
                reasons.append("INVALID_QWEN_CATEGORY")
            elif v5 in ALLOWED_CLASSES and qwen_category != v5:
                reasons.append("V5_QWEN_CATEGORY_DISAGREEMENT")
        request = item.get("request_id")
        if request is not None and (not isinstance(request, str) or not request.strip()):
            raise ValueError(f"row {i}: invalid request_id")
        for task in ("tags", "vqa", "copy"):
            reasons.extend(_binding_issues(case, inst, request, task.upper(), item.get(task)))
        question = item.get("vqa_question")
        if not isinstance(question, str) or not question.strip():
            reasons.append("VQA_QUESTION_NOT_PROVIDED")
        answer = _text(item.get("vqa"))
        if not answer:
            reasons.append("VQA_EMPTY_RESPONSE")
        elif ABSTENTION.search(answer):
            reasons.append("VQA_ABSTENTION_REQUIRES_QUESTION_REVIEW")
        copy = _text(item.get("copy"))
        if not copy:
            reasons.append("COPY_EMPTY_RESPONSE")
        elif FRAME_META.search(copy):
            reasons.append("COPY_CONTAINS_FRAME_DEBUG_TEXT")
        if item.get("duplicate_candidate") is True:
            reasons.append("UPSTREAM_DUPLICATE_CANDIDATE")
        if item.get("duplicate_candidate") not in (None, True, False):
            reasons.append("INVALID_UPSTREAM_DUPLICATE_FLAG")
        outputs.append({
            "case_id": case, "instance_id": inst, "v5_category": v5,
            "qwen_category_candidate": tags.get("category") if tags else None,
            "bbox_xyxy": list(bbox) if _valid_box(bbox) else None,
            "flags": list(dict.fromkeys(reasons)),
            "vqa_verification": "question_missing" if "VQA_QUESTION_NOT_PROVIDED" in reasons else "requires_human_reference_review",
            "copy_verification": "requires_visual_and_policy_review",
            "routing_echo_is_not_visual_binding_proof": True,
            "release_allowed": False,
            "original_record_sha256": _stable_hash(item),
        })
    # Pairwise geometric cue, not a truth label; never removes or chooses a box.
    groups: dict[str, list[dict[str, Any]]] = {}
    for record in outputs:
        groups.setdefault(record["case_id"], []).append(record)
    pairs = []
    for case, records in groups.items():
        for a, b in combinations(records, 2):
            if a["bbox_xyxy"] is None or b["bbox_xyxy"] is None:
                continue
            ratio = _overlap_by_smaller_box(a["bbox_xyxy"], b["bbox_xyxy"])
            if ratio < duplicate_overlap:
                continue
            pairs.append({"case_id": case, "instance_ids": [a["instance_id"], b["instance_id"]],
                          "smaller_box_coverage": round(ratio, 6), "confirmed_same_garment": False})
            for r in (a, b):
                if "GEOMETRIC_OVERLAP_REQUIRES_REVIEW" not in r["flags"]:
                    r["flags"].append("GEOMETRIC_OVERLAP_REQUIRES_REVIEW")
    for row in outputs:
        # Not silently downgraded to PASS when some fields happen to agree.
        row["service_action"] = "BLOCK_REVIEW" if row["flags"] else "REVIEW_REQUIRED"
    summary = Counter(f for row in outputs for f in row["flags"])
    return {
        "schema": "prd32_service_output_guard_v1",
        "scope": "GT_FREE_SERVICE_POSTPROCESS_DIAGNOSTIC_ONLY",
        "service_status": "REVIEW_REQUIRED_NOT_RELEASED",
        "instance_count": len(items),
        "flag_counts": dict(sorted(summary.items())),
        "instances": outputs,
        "geometric_overlap_pairs": pairs,
        "automatic_deduplication_performed": False,
        "automatic_category_override_performed": False,
        "model_inference_performed_by_guard": False,
        "human_ground_truth_used": False,
        "independent_accuracy_measured": False,
        "copy_publish_allowed": False,
        "official_prd_acceptance": False,
        "interpretation": "Routing metadata can detect wiring mismatches, not visual binding failures; overlapping boxes are review cues, not confirmed duplicate truth.",
        "input_sha256": _stable_hash(items),
    }
